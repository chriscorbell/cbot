#!/usr/bin/env bash
# Builds install.sh and uninstall.sh from their parts in scripts/install/:
#
#   scripts/bundle.sh [<folder>]    # write both scripts there (scripts/ when left out)
#
# `curl ... | bash` fetches one file, so each script is its parts joined in the order below, with main
# called on the last line: a download cut short runs nothing. Neither script is committed:
# scripts/build-release.sh bundles them into every build, GitHub Actions attaches them to each release
# (where the install and uninstall commands download them), and scripts/test_install.py tests a
# fresh bundle. Edit the parts.
set -euo pipefail

scripts="$(cd "$(dirname "$0")" && pwd)"
parts="$scripts/install"
out="${1:-$scripts}"
mkdir -p "$out"

# common.sh is in both: the output helpers, the top of the full screen, and become_root.
INSTALL=(install-header common install-output install-tui install-machine install-release install-done install-main)
UNINSTALL=(uninstall-header common uninstall-output uninstall-tui uninstall-steps uninstall-main)

# bundle <part>...: the script, on stdout.
bundle() {
  local part first=true
  echo '#!/usr/bin/env bash'
  echo '# Generated by scripts/bundle.sh from scripts/install/ in Dispatch'"'"'s source; edit those.'
  for part in "$@"; do
    $first || echo
    first=false
    cat "$parts/$part.sh"
  done
  printf '\nmain\n'
}

for name in install uninstall; do
  if [ "$name" = install ]; then list=("${INSTALL[@]}"); else list=("${UNINSTALL[@]}"); fi
  bundle "${list[@]}" >"$out/$name.sh.new"
  chmod 755 "$out/$name.sh.new"
  mv "$out/$name.sh.new" "$out/$name.sh"
done
