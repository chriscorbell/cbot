#!/usr/bin/env bash
# Builds scripts/install.sh and scripts/uninstall.sh from their parts in scripts/install/.
#
#   scripts/bundle.sh           # write both scripts
#   scripts/bundle.sh --check   # fail if either differs from its parts (CI runs this)
#
# `curl ... | bash` fetches one file, so each script is its parts joined in the order below, with main
# called on the last line: a download cut short runs nothing. Both scripts are committed, because
# that is what the curl command and the app's updates run. Edit the parts, then run this.
set -euo pipefail

scripts="$(cd "$(dirname "$0")" && pwd)"
parts="$scripts/install"

# common.sh is in both: the output helpers, the top of the full screen, and become_root.
INSTALL=(install-header common install-output install-tui install-machine install-release install-done install-main)
UNINSTALL=(uninstall-header common uninstall-output uninstall-tui uninstall-steps uninstall-main)

# bundle <part>...: the script, on stdout.
bundle() {
  local part first=true
  echo '#!/usr/bin/env bash'
  echo '# Generated by scripts/bundle.sh from scripts/install/; edit those, then run scripts/bundle.sh.'
  for part in "$@"; do
    $first || echo
    first=false
    cat "$parts/$part.sh"
  done
  printf '\nmain\n'
}

check=false
case "${1:-}" in
  '') ;;
  --check) check=true ;;
  *) echo "Usage: $0 [--check]" >&2; exit 2 ;;
esac

status=0
for name in install uninstall; do
  if [ "$name" = install ]; then list=("${INSTALL[@]}"); else list=("${UNINSTALL[@]}"); fi
  out="$scripts/$name.sh"
  if $check; then
    if ! diff -u "$out" <(bundle "${list[@]}") >&2; then
      echo "scripts/$name.sh doesn't match its parts in scripts/install/. Run scripts/bundle.sh and commit it." >&2
      status=1
    fi
  else
    bundle "${list[@]}" >"$out.new"
    chmod 755 "$out.new"
    mv "$out.new" "$out"
  fi
done
exit "$status"
